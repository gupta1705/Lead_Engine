#!/usr/bin/env python3
"""manual_lead.py -- a lead a person found on their own, and the email they write to it.

The owner, 2026-10-23: "Add a feature to send custom mail to a lead that we find on our own, as in lead is not
generated by software and then there should be an option to select the category it belongs to and then the usual".

On the Leads page, Add a lead: the person picks the project the lead belongs to, says who it is (the company, show
or startup, and its website, country and city if they know them) and who the email goes to (name, role, address),
writes the email and approves it. "The usual" is everything after that, as for an email the software drafted:
  * it goes out from the approver's own Gmail, inside its daily limit, in the project's sending window on the
    recipient's clock (the country and city are what that clock is read from, tools/send_window.py);
  * it is copied to the project's default CC unless switched off, and signed with the approver's name and title
    over the project's footer;
  * one follow-up four days later if nobody replies (the project's follow-up template), stopped by any reply;
  * LCX Services: it pitches the one service the person picks, and carries the deck its first emails carry.

The lead is a row like any other (source 'manual'; shortlisted, then contacted once the email goes), so it is on
the Leads page and the board, and the one-first-email-per-company rule holds, across every project (the approval
check refuses an address or a company another project already wrote to):
  * a company already in the project is used, never added twice: the same address, the same domain, or the same
    name with no domain;
  * one in conversation or already emailed is refused;
  * a draft the software wrote for it and nobody approved yet is replaced by the person's email;
  * one that was rejected or archived is reopened, and the page says so before anyone approves.

The address is the person's word for it. Apollo never saw it, and four projects send only to Apollo-verified
addresses (sql/38), so sql/42 lets a contact a person typed in (source 'manual', verifier 'person') through. This
module checks what it can for free first:
  * the address reads as one;
  * it is not one of our own;
  * the lead is not TVF itself (self_exclusion);
  * its country is not one the project never emails (geography.disallowed_countries: consent law;
    unpayable_countries). The country the person gives is taken, or else the address's or site's country domain.
Whether its domain exists is only a warning: a domain can take mail without a website.

`run(cur, body, person, apply=False)` does all of it. With apply=False (the page asking as the person types)
nothing is kept: every row it writes is rolled back. With apply=True the lead, its contact and the approved email are
kept only when the email can go; otherwise none of them is.
"""
import datetime as dt
import re
import time

import outreach_compose as comp

SOURCE = "manual"              # entities.source and contacts.source
VERIFIER = "person"            # contacts.verifier: a person vouched for the address (sql/42)
OPEN = ("discovered", "enriched", "scored", "ready_for_review", "shortlisted")
CLOSED = {"contacted": "already contacted", "in_conversation": "in conversation with us"}
REOPENS = ("rejected", "archived")
# contact_rank's own test of an address (sql/28): what fails it is never written to
EMAIL_RE = re.compile(r"^[a-z0-9._%+\-]+@[a-z0-9.\-]+\.[a-z]{2,}$")
FREE_MAIL = {"gmail.com", "googlemail.com", "yahoo.com", "yahoo.co.in", "yahoo.co.uk", "hotmail.com",
             "outlook.com", "live.com", "msn.com", "icloud.com", "me.com", "mac.com", "aol.com", "rediffmail.com",
             "proton.me", "protonmail.com", "gmx.com", "gmx.de", "mail.com", "yandex.com", "zoho.com"}
LIMITS = {"company": 160, "website": 200, "country": 60, "city": 80, "name": 120, "role": 120, "email": 200}
TEXT = ("company", "website", "country", "city", "name", "role", "email", "service")
_DNS = {}                      # domain -> (answers, when): the page asks again as the person types


class Problems(ValueError):
    """What the person must fix before anything can be added: {field: why}; "lead" is the lead as a whole."""

    def __init__(self, problems):
        super().__init__("; ".join(problems.values()))
        self.problems = problems


def now_iso():
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def norm_domain(v):
    s = str(v or "").strip().lower()
    s = re.sub(r"^[a-z]+://", "", s).split("/")[0].split("?")[0].split("#")[0].split("@")[-1].split(":")[0]
    s = re.sub(r"^www\.", "", s).strip(".")
    return s if re.match(r"^[a-z0-9]([a-z0-9\-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9\-]*[a-z0-9])?)*\.[a-z]{2,}$", s) else None


def _one_line(v, n):
    return " ".join(str(v or "").split())[:n]


def services(cfg):
    """The services an LCX Services email may pitch (the deck's), or None in a project without lead_service."""
    if "lead_service" not in (cfg or {}):
        return None
    gp = ((cfg.get("outreach") or {}).get("generated_pitch") or {})
    return [x for x in (gp.get("all_services") or list(gp.get("service_lines") or {})) if isinstance(x, str)]


def first_email_files(cfg):
    """The files the project's first emails carry (LCX Services: its deck), as template paths."""
    for t in ((cfg or {}).get("outreach") or {}).get("templates") or []:
        if isinstance(t, dict) and t.get("kind") != "follow_up" and t.get("attachments"):
            return [p for p in t["attachments"] if isinstance(p, str)]
    return []


def project(cfg):
    """What the page shows for a project before anything is typed: what its lead is called, the services it
    may pitch, the files its first emails carry, its follow-up and its default CC."""
    import outreach_policy as pol
    o = (cfg or {}).get("outreach") or {}
    steps = pol.followup_steps(o)
    return {"entity_label": ((cfg or {}).get("ui") or {}).get("entity_label") or "company",
            "lead_first": ((cfg or {}).get("ui") or {}).get("lead_first") == "person",
            "services": services(cfg),
            "files": [p.split("/")[-1] for p in first_email_files(cfg)],
            "follow_up_days": int(steps[0]["after_days"]) if steps else None,
            "default_cc": [str(a).strip().lower() for a in (o.get("default_cc") or []) if str(a).strip()]}


def domain_answers(domain):
    """Does anything answer at this domain? True / False / None (DNS could not say). Cached ten minutes."""
    got = _DNS.get(domain)
    if got and time.monotonic() - got[1] < 600:
        return got[0]
    from enrich_sitescrape import resolves
    ans = resolves(domain)
    _DNS[domain] = (ans, time.monotonic())
    return ans


def read(body, cfg):
    """-> (spec, problems, warnings) from what the person typed. Nothing is looked up in the database here."""
    import send_window as sw
    b = body or {}
    s = {k: _one_line(b.get(k), LIMITS.get(k, 200)) for k in TEXT}
    s["email"] = s["email"].lower().strip(" <>")
    problems, warnings = {}, {}
    label = project(cfg)["entity_label"]
    if not s["company"]:
        problems["company"] = "Write the %s's name." % label
    if not s["email"]:
        problems["email"] = "Write the address the email goes to."
    elif not EMAIL_RE.match(s["email"]):
        problems["email"] = "That does not read as an email address."
    s["email_domain"] = s["email"].split("@", 1)[1] if "@" in s["email"] and "email" not in problems else None
    s["website_domain"] = norm_domain(s["website"]) if s["website"] else None
    if s["website"] and not s["website_domain"]:
        problems["website"] = "Write the website as example.com."
    # the lead's own domain: its site, or the address's when that is not a free mailbox
    s["domain"] = s["website_domain"] or (s["email_domain"] if s["email_domain"] not in FREE_MAIL else None)
    s["iso"] = None
    if s["country"]:
        s["iso"] = sw.country_iso(s["country"])
        if not s["iso"]:
            problems["country"] = "Not a country we know. Try its name (United States) or its code (US)."
    geo = (cfg or {}).get("geography") or {}
    never = {str(c).upper(): "disallowed" for c in geo.get("disallowed_countries") or []}
    never.update({str(c).upper(): "unpayable" for c in geo.get("unpayable_countries") or []})
    seen = s["iso"]
    where = "country"
    if not seen:
        # no country given: the address's or the site's country domain is evidence of one (".de")
        for field, dom in (("email", s["email_domain"]), ("website", s["website_domain"])):
            tld = (dom or "").rsplit(".", 1)[-1].upper()
            if tld in never:
                seen, where = tld, field
                break
    if seen and seen in never and where not in problems:
        place = sw.tp.ISO_NAME.get(seen, seen) if hasattr(sw, "tp") else seen
        why = ("cold business email there needs consent first" if never[seen] == "disallowed"
               else "it cannot be paid from there")
        problems[where] = ("This project does not email leads in %s: %s.%s" % (
            place, why, "" if where == "country" else " If the lead is somewhere else, write its country."))
    choices = services(cfg)
    if choices is None:
        s["service"] = ""
    elif s["service"] not in choices:
        problems["service"] = "Pick the service this email pitches."
    return s, problems, warnings


def _own(cur, cfg):
    """Addresses that are ours: every login, every connected Gmail and its aliases, the project's default CC."""
    import mailbox_store as store
    cur.execute("select lower(email) as e from app_users")
    own = {r["e"] if isinstance(r, dict) else r[0] for r in cur.fetchall()}
    for m in store.mailboxes(cur):
        own.add(m["address"].lower())
        own |= {a["address"].lower() for a in (m.get("send_as") or []) if isinstance(a, dict) and a.get("address")}
    own |= set(project(cfg)["default_cc"])
    return own


def _find(cur, seg_id, s):
    """The lead already in this project: the same address, the same domain, or the same name with no domain."""
    cols = ("select e.id, e.name, e.domain, e.status, e.status_reason, e.status_changed_at, e.metadata, e.source"
            " from entities e")
    cur.execute(cols + " join contacts c on c.entity_id = e.id where e.segment_id = %s and lower(btrim(c.email)) = %s"
                " order by (e.status = any(%s)) desc, e.updated_at desc limit 1 for update of e",
                (seg_id, s["email"], list(OPEN)))
    row = cur.fetchone()
    if not row and s["domain"]:
        cur.execute(cols + " where e.segment_id = %s and e.domain = %s for update", (seg_id, s["domain"]))
        row = cur.fetchone()
    if not row:
        cur.execute(cols + " where e.segment_id = %s and e.domain is null and lower(e.name) = lower(%s)"
                    " limit 1 for update", (seg_id, s["company"]))
        row = cur.fetchone()
    return dict(row) if row else None


def _elsewhere(cur, slug, email):
    """Emails to this address from our other projects: which project and when, for the person. The refusal itself
    is the approval check's (outreach_policy.DUPLICATE_SQL: one first email per address, and per company, across
    every project), which reaches the page as the lead's problem."""
    cur.execute("select s.slug, s.name, o.status, coalesce(o.sent_at, o.approved_at) as at"
                " from outreach o join contacts c on c.id = o.contact_id join entities e on e.id = o.entity_id"
                " join segments s on s.id = e.segment_id where lower(btrim(c.email)) = %s and s.slug <> %s"
                " and o.direction = 'outbound' and o.status in ('approved', 'sending', 'send_unknown', 'sent')"
                " order by 4 desc nulls last limit 3", (email, slug))
    return [{"project": r["slug"], "status": r["status"], "at": r["at"].isoformat() if r["at"] else None}
            for r in cur.fetchall()]


def _prepare(cur, slug, seg_id, cfg, s, person):
    """Find or add the lead, its contact and the person's choice of recipient. -> what the page says about it.
    Raises Problems when the lead cannot be written to at all."""
    import psycopg2.extras
    by, who = person["email"], person.get("name") or person["email"]
    when = now_iso()
    found = _find(cur, seg_id, s)
    note = {"match": None, "reopens": None, "replaces_draft": False}
    meta = {}
    if s["iso"]:
        meta["hq_country"] = s["iso"]
    if s["city"]:
        meta["hq_city"] = s["city"]
    if s["name"] and project(cfg)["lead_first"]:
        meta["host"] = {"name": s["name"], "confidence": "high", "source": "person"}
    svc = s["service"] or None
    if svc:
        meta["lead_service"] = {"service": svc, "name": svc, "rule": "person", "basis": "person",
                                "reason": "Picked by %s when adding the lead" % who, "evidence": "", "set_by": by,
                                "decided_at": when}
    if found:
        eid = str(found["id"])
        note["match"] = {"id": eid, "name": found["name"], "status": found["status"],
                         "status_reason": found["status_reason"],
                         "since": found["status_changed_at"].isoformat() if found["status_changed_at"] else None}
        if found["status"] in CLOSED:
            raise Problems({"lead": "%s is already a lead in this project, %s. Its emails are in Outreach."
                                    % (found["name"], CLOSED[found["status"]])})
        old = found["metadata"] if isinstance(found["metadata"], dict) else {}
        # fill what the lead lacks; what it holds stays (a person's own service pick is theirs to change on the sheet)
        add = {k: v for k, v in meta.items() if k == "lead_service" or not old.get(k)}
        if svc and isinstance(old.get("lead_service"), dict):
            add["lead_service"] = dict(meta["lead_service"],
                                       rules_pick={k: old["lead_service"][k] for k in ("service", "rule", "basis")
                                                   if old["lead_service"].get(k) is not None})
        if found["status"] in REOPENS:
            note["reopens"] = found["status"]
            add["reopened_by_hand"] = {"by": by, "at": when, "was": found["status"],
                                       "reason": found["status_reason"]}
            cur.execute("update entities set status = 'shortlisted', status_reason = %s, status_changed_at = now(),"
                        " updated_at = now() where id = %s",
                        (("Reopened by %s, who wrote to it by hand" % who)[:300], eid))
        cur.execute("update entities set metadata = coalesce(metadata, '{}'::jsonb) || %s,"
                    " domain = coalesce(domain, %s), source_url = coalesce(source_url, %s), updated_at = now()"
                    " where id = %s", (psycopg2.extras.Json(add), s["domain"], s["website"] or None, eid))
        # a first email the software drafted and nobody approved: the person's own replaces it
        cur.execute("update outreach set status = 'cancelled', stopped_reason = %s, updated_at = now()"
                    " where entity_id = %s and direction = 'outbound' and status = 'drafted'"
                    " and coalesce(sequence_step, 0) = 0 returning id",
                    (("replaced by an email %s wrote" % who)[:200], eid))
        note["replaces_draft"] = bool(cur.fetchall())
    else:
        meta["added_by_hand"] = {"by": by, "name": who, "at": when}
        cur.execute("insert into entities (segment_id, name, domain, source, source_url, metadata, status,"
                    " status_reason, status_changed_at) values (%s, %s, %s, %s, %s, %s, 'shortlisted', %s, now())"
                    " returning id",
                    (seg_id, s["company"], s["domain"], SOURCE, s["website"] or None, psycopg2.extras.Json(meta),
                     ("Added by hand by %s" % who)[:300]))
        eid = str(cur.fetchone()["id"])
    cur.execute("select id, full_name, role_title, email_status, source,"
                " contact_allowed(entity_id, source, verifier, email_status) as allowed from contacts"
                " where entity_id = %s and lower(btrim(email)) = %s", (eid, s["email"]))
    c = cur.fetchone()
    if c and c["email_status"] == "invalid":
        raise Problems({"email": "This address bounced before: it is marked invalid on the lead."})
    if c:
        cid = str(c["id"])
        cur.execute("update contacts set full_name = coalesce(nullif(btrim(full_name), ''), %s),"
                    " role_title = coalesce(nullif(btrim(role_title), ''), %s), updated_at = now() where id = %s",
                    (s["name"] or None, s["role"] or None, cid))
        if not c["allowed"]:
            # an address the project could not use (scraped, in an Apollo project): the person vouches for it now
            cur.execute("update contacts set source = %s, verifier = %s, notes = btrim(concat_ws(E'\\n', notes, %s)),"
                        " updated_at = now() where id = %s",
                        (SOURCE, VERIFIER, "Confirmed by %s on %s (was %s)" % (by, when[:10], c["source"] or "unknown"),
                         cid))
    else:
        cur.execute("insert into contacts (entity_id, full_name, role_title, email, email_status, verifier, source,"
                    " notes) values (%s, %s, %s, %s, 'unverified', %s, %s, %s) returning id",
                    (eid, s["name"] or None, s["role"] or None, s["email"], VERIFIER, SOURCE,
                     "Typed in by %s on %s" % (by, when[:10])))
        cid = str(cur.fetchone()["id"])
    # the email goes to exactly this person: the same choice the lead sheet saves (tools/recipient_selection.py)
    cur.execute("update entities set metadata = jsonb_set(coalesce(metadata, '{}'::jsonb), '{outreach_recipient}', %s),"
                " updated_at = now() where id = %s",
                (psycopg2.extras.Json({"contact_id": cid, "email": s["email"], "chosen_by": by, "chosen_at": when}),
                 eid))
    return eid, note


def run(cur, body, person, apply=False, segments=None, approve=True):
    """-> {"project", "problems", "warnings", "match", "ready", "skipped", "footer", "lead_id", "outreach_id"}.

    `approve=False` (the API and MCP, app/api_v1.py): the email is kept as a draft in Outreach, Drafts, for a person
    to read and approve in the app; nothing a program writes goes out on its own.

    `segments`: the slugs this deployment shows (app/main.segment_rows). `person`: {email, name, title}. Raises
    comp.Refused for the email itself (an empty subject, an unknown field) and comp.NeedsProfile."""
    import apollo_store
    import outreach_policy as pol
    b = body or {}
    if not (person and person.get("name") and person.get("title")):
        raise comp.NeedsProfile("Add your name and title first (the account menu at the bottom of the sidebar): "
                                "the emails you write are signed with them.")
    slug = str(b.get("project") or "").strip()
    cur.execute("select id, slug, config from segments where slug = %s and is_active", (slug,))
    seg = cur.fetchone()
    if not seg or (segments is not None and slug not in segments):
        raise Problems({"project": "Pick the project this lead belongs to."})
    import draft_render as dr
    cfg = seg["config"] or {}
    o = pol.outreach_config(cur, slug)
    # the sign-off under the email, shown while the rest is still being typed
    out = {"project": dict(project(cfg), slug=slug), "problems": {}, "warnings": {}, "match": None,
           "ready": [], "skipped": [], "footer": dr.footer_for(o, person["name"], person["title"]),
           "lead_id": None, "outreach_id": None, "elsewhere": []}
    s, problems, warnings = read(b, cfg)
    if s["email"] and "email" not in problems:
        if s["email"] in _own(cur, cfg):
            problems["email"] = "That is one of our own addresses."
        else:
            out["elsewhere"] = _elsewhere(cur, slug, s["email"])
    if "company" not in problems:
        for dom in dict.fromkeys([s["domain"], s["email_domain"]]):
            mine = apollo_store.excluded({"name": s["company"], "primary_domain": dom}, cfg.get("self_exclusion"))
            if mine:
                what = re.search(r"\(([^)]*)\)", mine)
                problems["company"] = "That is TVF itself (%s), never a lead." % (what.group(1) if what else mine)
                break
    if s["email_domain"] and "email" not in problems and domain_answers(s["email_domain"]) is False:
        warnings["email"] = "Nothing answers at %s. Check the address before you approve." % s["email_domain"]
    out.update(problems=problems, warnings=warnings)
    if problems:
        return out
    files = []
    if b.get("attach", True):
        for p in first_email_files(cfg):
            try:
                files.append(pol.attachment_record(p))
            except (ValueError, OSError) as e:
                out["problems"] = {"lead": "The project's attachment cannot go: %s" % e}
                return out
    cur.execute("savepoint manual_lead")
    keep = False
    try:
        try:
            eid, note = _prepare(cur, slug, seg["id"], cfg, s, person)
        except Problems as e:
            out["problems"] = e.problems
            return out
        out.update(lead_id=eid, **note)
        got = comp.plan(cur, slug, [eid], b.get("subject") or "", b.get("body") or "", person, o, apply=apply,
                        cc=b.get("cc"), service=s["service"] or None, attachments=files or None,
                        approve=approve)
        out.update(ready=got["ready"], skipped=got["skipped"], footer=got["footer"])
        if got["skipped"]:
            out["problems"] = {"lead": "It cannot be written to: %s." % got["skipped"][0]["reason"]}
        elif apply and got["ready"]:
            out["outreach_id"] = got["ready"][0].get("outreach_id")
            keep = True
    finally:
        cur.execute("release savepoint manual_lead" if keep else "rollback to savepoint manual_lead")
        if not keep:
            cur.execute("release savepoint manual_lead")
    if not keep:
        out["lead_id"] = out["lead_id"] if out["match"] else None
    return out
