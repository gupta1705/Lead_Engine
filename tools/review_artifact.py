"""review_artifact.py -- render the review queue as a self-contained HTML page.

The terminal sheet (review_sheet.py) is fine for a glance; it is a poor surface
for making ten decisions about real companies. This builds the same data as a
page you can actually work through, and it is generated from the live database
rather than hand-written, so it regenerates every week for free and can never
drift from what is actually in `entities`.

It is a precursor to P18 (review queue in the browser) -- deliberately so. The
information design here is the part worth keeping: every rubric criterion gets a
bar, and a criterion that was NEVER ASSESSED renders as a visibly empty slot
rather than being left out. Invariant 1 says an unassessed criterion is excluded
from the score entirely; if it were simply absent from the page, a reviewer
would read a high score without noticing how little it was computed from.

The output is GITIGNORED on purpose. It is built from the live database, so a
committed copy cannot be regenerated by anyone who clones the repo, goes stale
the instant a lead is dispositioned, and carries real contact names, emails and
internal verdicts on named companies. Run the script; do not commit the result.

Usage:  python tools/review_artifact.py [-o out.html]
"""
